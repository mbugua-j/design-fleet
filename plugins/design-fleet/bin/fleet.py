#!/usr/bin/env python3
"""design-fleet — materialise the fleet's agents under a chosen crew's names.

The plugin ships thirteen canonical stations. This script writes personalised
copies of them, renamed to a crew pack, into your project or user agents
directory — rewriting every cross-reference between stations so the pipeline
still hands over correctly.

  fleet.py crews                          list the available crew packs
  fleet.py stations                       list the canonical stations
  fleet.py show --crew avengers           preview the renaming
  fleet.py new-crew --name starwars       name every station yourself, interactively
  fleet.py apply --crew avengers --scope project --dir .
  fleet.py apply --crew flintstones --scope user --stations designr,contrarian
  fleet.py dashboard                      open the local fleet activity dashboard

Generated files are plain markdown. Edit them freely; re-running apply will
not overwrite an existing file unless you pass --force.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parent.parent
AGENTS_DIR = PLUGIN_ROOT / "agents"
CREWS_DIR = PLUGIN_ROOT / "crews"
SKILLS_DIR = PLUGIN_ROOT / "skills"

# Crews you create live outside the plugin, so a plugin update cannot delete them.
USER_CREWS_DIR = Path(os.environ.get("COPILOT_HOME", Path.home() / ".copilot")) / "design-fleet" / "crews"

GENERATED_MARK = "<!-- generated by design-fleet"

# Models the fleet has moved off. Checked against every agent file in the target
# directory, not only generated ones — a hand-written station on a retired model
# fails just as hard as a generated one.
RETIRED_MODEL = re.compile(
    r"^model:\s*(gemini-3\.1-pro-preview|gemini-3\.[567]-flash|claude-sonnet-4\.6|claude-opus-4\.[56])\s*$",
    re.MULTILINE,
)

CREW_ID = re.compile(r"^[a-z][a-z0-9-]{0,63}$")
MODEL_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,79}$")

# Names that cannot be a filename on Windows, whatever the extension.
RESERVED_NAMES = {
    "con", "prn", "aux", "nul",
    *(f"com{i}" for i in range(1, 10)),
    *(f"lpt{i}" for i in range(1, 10)),
}


def safe_crew_path(name: str) -> Path:
    """Resolve a crew file inside USER_CREWS_DIR, refusing anything that escapes it."""
    if not CREW_ID.fullmatch(name):
        sys.exit(
            f"error: '{name}' is not a valid crew id.\n"
            "       Use lowercase letters, digits and hyphens, starting with a letter."
        )
    root = USER_CREWS_DIR.resolve()
    target = (root / f"{name}.json").resolve()
    if target.parent != root:
        sys.exit(f"error: refusing to write outside {root}")
    return target


# --------------------------------------------------------------------------- data


def load_roles() -> dict:
    return json.loads((CREWS_DIR / "roles.json").read_text(encoding="utf-8"))


def canonical_ids() -> list[str]:
    return [s["id"] for s in load_roles()["stations"]]


def canonical_display() -> dict[str, str]:
    """Station id -> the name its shipped file uses (also its filename)."""
    return {s["id"]: s["display"] for s in load_roles()["stations"]}


def shipped_name_collisions(mapping: dict[str, str]) -> list[tuple[str, str]]:
    """Crew names that are also the name of a station the plugin already ships.

    Generated agents land beside the plugin's own, so a name that matches a
    shipped station leaves two agents called the same thing. Copilot CLI
    namespaces the plugin's copies, but pickers that hide the namespace show
    the pair identically and there is no way to tell which one runs.
    """
    shipped = {name.lower() for name in canonical_display().values()}
    return [(cid, mapping[cid]) for cid in canonical_ids()
            if cid in mapping and mapping[cid].lower() in shipped]


def crew_paths() -> dict[str, Path]:
    """Crew name -> file. User crews win over shipped ones of the same name."""
    found: dict[str, Path] = {}
    for directory in (CREWS_DIR, USER_CREWS_DIR):
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob("*.json")):
            if path.stem != "roles":
                found[path.stem] = path
    return found


def crew_problems(crew: dict, source: str) -> list[str]:
    problems: list[str] = []
    names = crew.get("names", {})
    models = crew.get("models", {})

    missing = [cid for cid in canonical_ids() if cid not in names]
    if missing:
        problems.append(f"{source}: missing names for: {', '.join(missing)}")

    # A station that merged into another is not a typo, so say what happened and
    # where the work went rather than reporting it as a name nobody recognises.
    retired = load_roles().get("retired", {})
    gone = [cid for cid in names if cid not in canonical_ids() and cid in retired]
    for cid in gone:
        problems.append(
            f"{source}: names '{cid}', which merged into '{retired[cid]}' — remove that "
            f"name, or run 'fleet.py new-crew' to rebuild the pack"
        )

    unknown = [cid for cid in names if cid not in canonical_ids() and cid not in retired]
    if unknown:
        problems.append(f"{source}: names stations that do not exist: {', '.join(unknown)}")

    unknown_models = [cid for cid in models if cid not in canonical_ids()]
    if unknown_models:
        problems.append(
            f"{source}: overrides models for stations that do not exist: "
            f"{', '.join(unknown_models)}"
        )
    invalid_models = [
        model for model in models.values()
        if not isinstance(model, str) or not MODEL_ID.fullmatch(model)
    ]
    if invalid_models:
        problems.append(
            f"{source}: unusable model ids: {', '.join(map(str, invalid_models))}"
        )

    chosen = [names[cid] for cid in canonical_ids() if cid in names]
    lowered = [n.lower() for n in chosen]
    dupes = sorted({n for n in lowered if lowered.count(n) > 1})
    if dupes:
        problems.append(f"{source}: reuses the same name for several stations: {', '.join(dupes)}")

    # A crew that renames some stations but leaves others on their shipped name
    # produces agents that collide with the ones the plugin already installs.
    # The all-identity case is the 'shipyard' pack, which documents the shipped
    # naming rather than renaming anything; `apply` refuses that one instead.
    collisions = shipped_name_collisions(names)
    if collisions and len(collisions) < len(canonical_ids()):
        listed = ", ".join(f"{cid} -> {name}" for cid, name in collisions)
        problems.append(
            f"{source}: reuses names the plugin already ships: {listed} — rename those, "
            "or the generated agents appear twice under one name"
        )

    bad = [n for n in chosen if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", n)]
    if bad:
        problems.append(
            f"{source}: unusable names: {', '.join(bad)} "
            "(letters, digits, dots, hyphens and underscores only — no spaces)"
        )

    # Each name becomes a filename, so it has to survive every filesystem.
    unportable = [n for n in chosen if n.lower() in RESERVED_NAMES or n.endswith(".") or len(n) > 64]
    if unportable:
        problems.append(
            f"{source}: names that cannot be filenames everywhere: {', '.join(unportable)} "
            "(reserved on Windows, ends with a dot, or over 64 characters)"
        )
    return problems


def validate_crew(crew: dict, source: str) -> dict:
    problems = crew_problems(crew, source)
    if problems:
        sys.exit("error: " + "\n       ".join(problems))
    return crew


def load_crew(name: str) -> dict:
    paths = crew_paths()
    if name not in paths:
        sys.exit(f"error: no crew named '{name}'. Available: {', '.join(sorted(paths))}")
    return validate_crew(json.loads(paths[name].read_text(encoding="utf-8")), name)


def list_crews() -> list[tuple[dict, bool]]:
    out = []
    for name, path in sorted(crew_paths().items()):
        crew = json.loads(path.read_text(encoding="utf-8"))
        out.append((crew, path.parent == USER_CREWS_DIR))
    return out


# ---------------------------------------------------------------------- renaming


def rename_text(text: str, mapping: dict[str, str]) -> str:
    """Rewrite every station reference, in one atomic pass.

    Substitution runs via placeholders so a rename can never cascade: if a crew
    maps `surveyor` -> `lookout`, the real `lookout` is not renamed a second time.

    A station name is a proper noun, so the crew's own casing always wins —
    `**shipwright**` becomes `**Han**`, not `**han**`.

    Underscores count as word characters, so an identifier like `my_surveyor_tool`
    is left alone rather than being rewritten into `my_Han_tool`.
    """
    ids = sorted(mapping, key=len, reverse=True)
    placeholders: dict[str, str] = {}

    for index, canonical in enumerate(ids):
        token = f"\x00{index}\x00"
        placeholders[token] = mapping[canonical]
        pattern = re.compile(rf"(?<![A-Za-z0-9_]){re.escape(canonical)}(?![A-Za-z0-9_])", re.IGNORECASE)
        text = pattern.sub(token, text)

    for token, value in placeholders.items():
        text = text.replace(token, value)
    return text


def split_front_matter(text: str) -> tuple[str, str]:
    if not text.startswith("---"):
        sys.exit("error: agent file has no front matter")
    end = text.index("\n---", 3)
    return text[: end + 4], text[end + 4 :]


def plugin_version() -> str:
    manifest = PLUGIN_ROOT / ".github" / "plugin" / "plugin.json"
    try:
        return json.loads(manifest.read_text(encoding="utf-8")).get("version", "unknown")
    except (OSError, json.JSONDecodeError):
        return "unknown"


def source_digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def build_agent(
    canonical: str,
    mapping: dict[str, str],
    crew_name: str,
    model_overrides: dict[str, str] | None = None,
) -> tuple[str, str]:
    source = AGENTS_DIR / f"{canonical_display()[canonical]}.agent.md"
    if not source.exists():
        sys.exit(f"error: missing canonical agent {source}")

    front, body = split_front_matter(source.read_text(encoding="utf-8"))
    new_name = mapping[canonical]

    front = rename_text(front, mapping)
    front = re.sub(r"^name:.*$", f"name: {new_name}", front, count=1, flags=re.MULTILINE)
    if model_overrides and canonical in model_overrides:
        front = re.sub(
            r"^model:.*$",
            f"model: {model_overrides[canonical]}",
            front,
            count=1,
            flags=re.MULTILINE,
        )
    body = rename_text(body, mapping)

    # Provenance lets `fleet.py status` tell you when the shipped station has moved
    # on — a model retirement, say — while your personalised copy has not.
    note = (
        f"\n{GENERATED_MARK} — station '{canonical}' as '{new_name}' (crew: {crew_name})\n"
        f"     from design-fleet v{plugin_version()} source {source_digest(source)}.\n"
        "     This file is yours: edit it to refine the station. Re-running\n"
        "     `fleet.py apply` will not overwrite it unless you pass --force.\n"
        "     Run `fleet.py status` to see if the shipped version has changed. -->\n"
    )
    # The filename is the name Copilot shows in its agent picker, so it keeps the crew's casing.
    return f"{new_name}.agent.md", front + body.rstrip() + "\n" + note


def target_dir(scope: str, project_dir: Path) -> Path:
    if scope == "user":
        return Path(os.environ.get("COPILOT_HOME", Path.home() / ".copilot")) / "agents"
    return project_dir / ".github" / "agents"


# ---------------------------------------------------------------------- commands


EDIT_ALIASES = {"edit", "multiedit", "write", "notebookedit"}
SHELL_ALIASES = {"execute", "shell", "bash", "powershell"}


def parse_front_list(front: str, field: str) -> list[str] | None:
    """Declared one-line front matter list, or None when the field is absent."""
    found = re.search(rf"^{re.escape(field)}:\s*(.+)$", front, re.MULTILINE)
    if not found:
        return None
    return [t.strip().strip("'\"") for t in found.group(1).strip("[] ").split(",") if t.strip()]


def parse_tools(front: str) -> list[str] | None:
    """Declared tool list, or None when the agent inherits every tool."""
    return parse_front_list(front, "tools")


def cmd_check(args: argparse.Namespace) -> None:
    """Validate the fleet. Run before opening a pull request; CI runs it too."""
    problems: list[str] = []
    roles = load_roles()
    display = canonical_display()

    required_front = ("name:", "description:")
    skill_names: set[str] = set()

    for skill_dir in sorted(path for path in SKILLS_DIR.iterdir() if path.is_dir()):
        skill_file = skill_dir / "SKILL.md"
        if not skill_file.exists():
            problems.append(f"skills/{skill_dir.name}: SKILL.md is missing")
            continue

        skill_text = skill_file.read_text(encoding="utf-8")
        if not skill_text.startswith("---"):
            problems.append(f"skills/{skill_dir.name}/SKILL.md: no front matter")
            continue
        try:
            skill_front = skill_text[: skill_text.index("\n---", 3)]
        except ValueError:
            problems.append(f"skills/{skill_dir.name}/SKILL.md: front matter is not closed")
            continue

        name = re.search(r"^name:\s*(.+)$", skill_front, re.MULTILINE)
        description = re.search(r"^description:\s*(.+)$", skill_front, re.MULTILINE)
        if not name:
            problems.append(f"skills/{skill_dir.name}/SKILL.md: front matter has no 'name:'")
        elif name.group(1).strip() != skill_dir.name:
            problems.append(
                f"skills/{skill_dir.name}/SKILL.md: name is '{name.group(1).strip()}' "
                f"but the directory is '{skill_dir.name}'"
            )
        else:
            skill_names.add(skill_dir.name)
        if not description:
            problems.append(f"skills/{skill_dir.name}/SKILL.md: front matter has no 'description:'")

    for station in roles["stations"]:
        cid, disp = station["id"], station["display"]
        path = AGENTS_DIR / f"{disp}.agent.md"
        if not path.exists():
            problems.append(f"roles.json lists '{cid}' but {disp}.agent.md is missing")
            continue

        text = path.read_text(encoding="utf-8")
        if not text.startswith("---"):
            problems.append(f"{path.name}: no front matter")
            continue
        front = text[: text.index("\n---", 3)]

        for key in required_front:
            if not re.search(rf"^{key}", front, re.MULTILINE):
                problems.append(f"{path.name}: front matter has no '{key}'")

        found = re.search(r"^name:\s*(.+)$", front, re.MULTILINE)
        if found and found.group(1).strip() != disp:
            problems.append(
                f"{path.name}: name is '{found.group(1).strip()}' but Copilot uses the "
                f"filename, so it must be '{disp}'"
            )

        # The model in the file is what actually runs; roles.json is what the
        # README and the family-independence claim are built from.
        model = re.search(r"^model:\s*(.+)$", front, re.MULTILINE)
        if model and model.group(1).strip() != station.get("model"):
            problems.append(
                f"{path.name}: model is '{model.group(1).strip()}' but roles.json says "
                f"'{station.get('model')}'"
            )

        # A station documented as a check must actually be denied the edit tool,
        # otherwise "cannot edit" is a promise rather than a constraint.
        tools = parse_tools(front)
        declared_skills = parse_front_list(front, "skills") or []
        if station.get("edits") is False:
            if tools is None:
                problems.append(
                    f"{path.name}: roles.json says it cannot edit, but it declares no "
                    "'tools:' — an unset list inherits every tool, including edit"
                )
            else:
                offending = [t for t in tools if t.lower() in EDIT_ALIASES]
                if offending:
                    problems.append(
                        f"{path.name}: roles.json says it cannot edit but tools include "
                        f"{', '.join(offending)}"
                    )
                shell = [t for t in tools if t.lower() in SHELL_ALIASES]
                if shell and not station.get("shellRequired"):
                    problems.append(
                        f"{path.name}: has shell ({', '.join(shell)}) so it can write files. "
                        "Set \"shellRequired\": true in roles.json to record that this is "
                        "deliberate and not a read-only guarantee."
                    )

        role_skills = set(station.get("skills", []))
        agent_skills = set(declared_skills)
        for skill_name in sorted(role_skills | agent_skills):
            if skill_name not in skill_names:
                problems.append(
                    f"{path.name}: unknown preloaded skill '{skill_name}'"
                )
        missing_from_agent = sorted(role_skills - agent_skills)
        extra_in_agent = sorted(agent_skills - role_skills)
        if missing_from_agent:
            problems.append(
                f"{path.name}: roles.json requires skill(s) "
                f"{', '.join(missing_from_agent)}, but front matter does not preload them"
            )
        if extra_in_agent:
            problems.append(
                f"{path.name}: front matter preloads skill(s) "
                f"{', '.join(extra_in_agent)} not declared in roles.json"
            )

        for field in ("group", "model", "purpose", "title"):
            if not station.get(field):
                problems.append(f"roles.json: station '{cid}' has no '{field}'")
        for field in ("needs", "optionalNeeds", "skills"):
            if field in station and not isinstance(station[field], list):
                problems.append(f"roles.json: station '{cid}' field '{field}' must be a list")
        if station.get("group") not in roles["groups"]:
            problems.append(f"roles.json: station '{cid}' is in unknown group '{station.get('group')}'")

    known_files = {f"{d}.agent.md" for d in display.values()}
    for path in sorted(AGENTS_DIR.glob("*.agent.md")):
        if path.name not in known_files:
            problems.append(f"{path.name} exists but is not listed in crews/roles.json")

    # CI must validate what the repository ships, not whatever crews happen to
    # exist in the machine's home directory.
    if getattr(args, "source_only", False):
        crews = {p.stem: p for p in sorted(CREWS_DIR.glob("*.json")) if p.stem != "roles"}
    else:
        crews = crew_paths()

    for name, path in sorted(crews.items()):
        crew = json.loads(path.read_text(encoding="utf-8"))
        problems.extend(crew_problems(crew, f"crews/{name}.json"))
        if not crew_problems(crew, name):
            for cid in canonical_ids():
                try:
                    build_agent(cid, crew["names"], name, crew.get("models", {}))
                except SystemExit as exc:
                    problems.append(f"crews/{name}.json: cannot render '{cid}': {exc}")

    if problems:
        print(f"✗ {len(problems)} problem(s):\n")
        for problem in problems:
            print(f"  - {problem}")
        sys.exit(1)

    scope = "shipped" if getattr(args, "source_only", False) else "available"
    print(f"✓ {len(roles['stations'])} stations, {len(crews)} {scope} crews — all valid")


def cmd_status(args: argparse.Namespace) -> None:
    """Show which of your personalised stations have fallen behind the shipped ones."""
    dest = target_dir(args.scope, Path(args.dir).resolve())
    if not dest.is_dir():
        sys.exit(f"error: no agents directory at {dest}")

    current = {canonical_display()[cid]: source_digest(AGENTS_DIR / f"{canonical_display()[cid]}.agent.md")
               for cid in canonical_ids()}

    rows, stale, edited, generated, unmanaged_retired = [], 0, 0, 0, 0
    for path in sorted(dest.glob("*.agent.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        on_retired_model = bool(RETIRED_MODEL.search(text))
        if GENERATED_MARK not in text:
            if on_retired_model:
                rows.append((path.name, "-", "yours (not generated) — RETIRED MODEL"))
                edited += 1
                unmanaged_retired += 1
            else:
                rows.append((path.name, "-", "yours (not generated)"))
            continue
        generated += 1
        found = re.search(r"station '([^']+)' as '([^']+)'.*?v(\S+) source (\w+)", text, re.S)
        if not found:
            rows.append((path.name, "-", "generated by an older version — re-apply to date it"))
            stale += 1
            continue
        cid, _, ver, digest = found.groups()
        shipped = current.get(canonical_display().get(cid, ""))
        if shipped is None:
            rows.append((path.name, ver, f"station '{cid}' no longer exists"))
        elif shipped == digest:
            rows.append((path.name, ver, "up to date"))
        else:
            rows.append((path.name, ver, "SHIPPED VERSION CHANGED — review and re-apply"))
            stale += 1
        if on_retired_model:
            rows[-1] = (rows[-1][0], rows[-1][1], "RETIRED MODEL — re-apply with --force")
            edited += 1

    width = max((len(r[0]) for r in rows), default=10)
    print(f"{dest}\n")
    for name, ver, note in rows:
        print(f"  {name:<{width}}  v{ver:<8} {note}")

    if stale or edited:
        print(f"\n{stale + edited} station(s) need attention. To take the shipped version of one:")
        print(f"  python3 {Path(__file__).name} apply --crew <yours> --scope {args.scope} "
              "--stations <station> --force")
        print("Keep a copy of your edits first — --force overwrites.")
        if unmanaged_retired:
            print("\nStations marked 'yours (not generated)' were not written by this script, so "
                  "--force would replace your own work rather than update it. Edit the model: "
                  "line in those by hand.")
    elif generated:
        print("\nAll generated stations match the shipped versions.")
    else:
        print("\nNo generated stations here — nothing to compare against the shipped versions.")


def cmd_dashboard(args: argparse.Namespace) -> None:
    """Run the local fleet activity dashboard."""
    server = PLUGIN_ROOT / "dashboard" / "server.py"
    if not server.is_file():
        sys.exit(f"error: dashboard server not found at {server}")
    command = [sys.executable, str(server), "--port", str(args.port)]
    if args.no_open:
        command.append("--no-open")
    completed = subprocess.run(command, check=False)
    raise SystemExit(completed.returncode)


def cmd_crews(_: argparse.Namespace) -> None:
    for crew, is_yours in list_crews():
        tag = "  (yours)" if is_yours else ""
        print(f"{crew['name']:<14} {crew['label']:<16} {crew.get('description', '')}{tag}")
        sample = ", ".join(f"{k} -> {v}" for k, v in list(crew["names"].items())[:3] if k.lower() != v.lower())
        if sample:
            print(f"{'':<14} e.g. {sample}")


def cmd_stations(_: argparse.Namespace) -> None:
    roles = load_roles()
    for group, label in roles["groups"].items():
        print(f"\n{label}")
        for station in roles["stations"]:
            if station["group"] != group:
                continue
            edits = "writes" if station["edits"] else "read-only"
            needs = f" needs: {', '.join(station['needs'])}" if station["needs"] else ""
            optional = (
                f" optional: {', '.join(station.get('optionalNeeds', []))}"
                if station.get("optionalNeeds")
                else ""
            )
            print(
                f"  {station['id']:<15} {station['display']:<16} "
                f"{station['model']:<24} {edits:<10}{needs}{optional}"
            )
            print(f"  {'':<15} {station['purpose']}")


def cmd_show(args: argparse.Namespace) -> None:
    crew = load_crew(args.crew)
    roles = {s["id"]: s for s in load_roles()["stations"]}
    print(f"Crew: {crew['label']} — {crew.get('description', '')}\n")
    print(f"  {'station':<15} {'becomes':<22} {'model':<24} role")
    for canonical, new_name in crew["names"].items():
        role = roles[canonical]
        model = crew.get("models", {}).get(canonical, role["model"])
        print(f"  {canonical:<15} {new_name:<22} {model:<24} {role['title']}")


def cmd_new_crew(args: argparse.Namespace) -> None:
    """Name every station yourself and save it as a reusable crew."""
    # Validate the destination before doing any work, so a bad name can never
    # reach the filesystem no matter which later branch runs.
    path = safe_crew_path(args.name)

    roles = {s["id"]: s for s in load_roles()["stations"]}
    names: dict[str, str] = {}
    models: dict[str, str] = {}

    for pair in args.set or []:
        if "=" not in pair:
            sys.exit(f"error: --set expects station=Name, got '{pair}'")
        station, value = pair.split("=", 1)
        station, value = station.strip(), value.strip()
        if station not in roles:
            sys.exit(f"error: unknown station '{station}'. Run `fleet.py stations` to see them.")
        names[station] = value

    for pair in args.model or []:
        if "=" not in pair:
            sys.exit(f"error: --model expects station=model, got '{pair}'")
        station, value = pair.split("=", 1)
        station, value = station.strip(), value.strip()
        if station not in roles:
            sys.exit(f"error: unknown station '{station}'. Run `fleet.py stations` to see them.")
        if not MODEL_ID.fullmatch(value):
            sys.exit(f"error: invalid model id '{value}'")
        models[station] = value

    missing = [cid for cid in canonical_ids() if cid not in names]
    if missing and not sys.stdin.isatty():
        sys.exit(
            "error: no name given for: " + ", ".join(missing) + "\n"
            "       Pass --set station=Name for each, or run interactively."
        )

    if missing:
        print(f"Naming your crew '{args.name}'. Press Enter to keep the suggested name.\n")
        for cid in missing:
            role = roles[cid]
            default = role["display"]
            print(f"  {role['title']} — {role['purpose']}")
            try:
                answer = input(f"  name for {cid} [{default}]: ").strip()
            except (EOFError, KeyboardInterrupt):
                sys.exit("\naborted")
            names[cid] = answer or default
            print()

    crew = {
        "name": args.name,
        "label": args.label or args.name.replace("-", " ").title(),
        "description": args.description or "Custom crew.",
        "names": {cid: names[cid] for cid in canonical_ids()},
    }
    if models:
        crew["models"] = models
    path = safe_crew_path(args.name)
    validate_crew(crew, args.name)
    USER_CREWS_DIR.mkdir(parents=True, exist_ok=True)
    if path.exists() and not args.force:
        sys.exit(f"error: {path} already exists; pass --force to replace it")
    path.write_text(json.dumps(crew, indent=2) + "\n", encoding="utf-8")

    print(f"Saved crew '{args.name}' to {path}")
    for cid in canonical_ids():
        print(f"  {cid:<15} -> {crew['names'][cid]}")
    print(f"\nNow write the agents:\n  python3 {Path(__file__).name} apply --crew {args.name} --scope user")


def cmd_apply(args: argparse.Namespace) -> None:
    crew = load_crew(args.crew)
    mapping = crew["names"]

    wanted = canonical_ids()
    if args.stations:
        requested = [s.strip() for s in args.stations.split(",") if s.strip()]
        unknown = [s for s in requested if s not in mapping]
        if unknown:
            sys.exit(f"error: unknown station(s): {', '.join(unknown)}")
        wanted = requested

    project_dir = Path(args.dir).resolve()
    dest = target_dir(args.scope, project_dir)

    # Writing a station under a name the plugin already uses leaves two agents
    # called the same thing. A crew that collides on only some stations is
    # rejected earlier, by crew_problems, so anything arriving here collides on
    # every station it was asked for: the crew is the shipped naming itself and
    # there is nothing to personalise.
    collisions = [(cid, name) for cid, name in shipped_name_collisions(mapping) if cid in wanted]
    if collisions and not args.allow_shipped_names:
        sys.exit(
            f"error: crew '{args.crew}' uses the names the plugin already ships, so there\n"
            f"       is nothing to personalise — these agents are installed already.\n"
            f"       Writing them would leave a second copy of every station under the\n"
            f"       same name, and a picker that hides the plugin namespace cannot tell\n"
            f"       them apart.\n\n"
            f"       Pick a different crew (fleet.py crews), or name your own with\n"
            f"       'fleet.py new-crew'. To render this pack anyway, for testing, pass\n"
            f"       --allow-shipped-names."
        )

    written, skipped = [], []
    if not args.dry_run:
        dest.mkdir(parents=True, exist_ok=True)

    for canonical in wanted:
        filename, content = build_agent(
            canonical,
            mapping,
            crew["name"],
            crew.get("models", {}),
        )
        path = dest / filename
        if path.exists() and not args.force:
            existing = path.read_text(encoding="utf-8", errors="replace")
            skipped.append((filename, "yours — edited" if GENERATED_MARK not in existing else "already present"))
            continue
        if not args.dry_run:
            path.write_text(content, encoding="utf-8")
        written.append(filename)

    verb = "Would write" if args.dry_run else "Wrote"
    print(f"{verb} {len(written)} station(s) to {dest}")
    for name in written:
        print(f"  + {name}")
    for name, why in skipped:
        print(f"  · {name} skipped ({why}); use --force to replace")

    if not args.dry_run and args.scope == "project":
        print(f"\nRun `/add-dir {project_dir}` in Copilot CLI, or restart it, to load them.")


def main() -> None:
    parser = argparse.ArgumentParser(prog="fleet.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("crews", help="list crew packs").set_defaults(func=cmd_crews)
    sub.add_parser("stations", help="list canonical stations").set_defaults(func=cmd_stations)
    check = sub.add_parser("check", help="validate the fleet (run before opening a pull request)")
    check.add_argument("--source-only", action="store_true",
                       help="validate only the crews this repository ships, ignoring your own")
    check.set_defaults(func=cmd_check)

    show = sub.add_parser("show", help="preview a crew's renaming")
    show.add_argument("--crew", required=True)
    show.set_defaults(func=cmd_show)

    new_crew = sub.add_parser("new-crew", help="name every station yourself and save it as a crew")
    new_crew.add_argument("--name", required=True, help="short id for the crew, e.g. starwars")
    new_crew.add_argument("--label", help="display label, e.g. 'Star Wars'")
    new_crew.add_argument("--description")
    new_crew.add_argument("--set", action="append", metavar="STATION=NAME",
                          help="name one station, e.g. --set designr=Luke (repeatable)")
    new_crew.add_argument("--model", action="append", metavar="STATION=MODEL",
                          help="override one station model, e.g. --model designr=gpt-5.6-sol")
    new_crew.add_argument("--force", action="store_true", help="replace an existing crew of this name")
    new_crew.set_defaults(func=cmd_new_crew)

    status = sub.add_parser("status", help="show which of your stations have fallen behind")
    status.add_argument("--scope", choices=["project", "user"], default="user")
    status.add_argument("--dir", default=".", help="project directory (scope=project)")
    status.set_defaults(func=cmd_status)

    dashboard = sub.add_parser(
        "dashboard",
        help="open the local fleet activity, model health and crew dashboard",
    )
    dashboard.add_argument("--port", type=int, default=8100)
    dashboard.add_argument("--no-open", action="store_true")
    dashboard.set_defaults(func=cmd_dashboard)

    apply_cmd = sub.add_parser("apply", help="write renamed agents")
    apply_cmd.add_argument("--crew", required=True)
    apply_cmd.add_argument("--scope", choices=["project", "user"], default="project")
    apply_cmd.add_argument("--dir", default=".", help="project directory (scope=project)")
    apply_cmd.add_argument("--stations", help="comma-separated subset of canonical station ids")
    apply_cmd.add_argument("--force", action="store_true", help="overwrite existing files")
    apply_cmd.add_argument("--dry-run", action="store_true")
    apply_cmd.add_argument("--allow-shipped-names", action="store_true",
                           help="write stations even where the crew reuses a shipped station's "
                                "name; you will have two agents under that name")
    apply_cmd.set_defaults(func=cmd_apply)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
